"""build_package.py · Taif / Palm House · builds the DELIVERY PACKAGE (the main branch's content) from the work branch's sources.

Run from the work branch, from anywhere:   python taif_house/package_src/build_package.py <out_dir>
It writes <out_dir>/package/ (the PDFs, the DXFs, the schedule CSV, the 3D renders) and <out_dir>/README.md, touching nothing in the repository except
output/*.dxf (regenerated by the DXF tools; restore them with git if you do not want them changed) and package_src/room_schedule.csv (regenerated).
Needs typst (0.13+ for the PDF merge) and pdftotext (Git for Windows: C:\\Program Files\\Git\\ucrt64\\bin) or pypdf for the page counts.
"""
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent          # taif_house
SRC = ROOT / "package_src"
if len(sys.argv) < 2:
    sys.exit("usage: build_package.py <out_dir>")
OUT = Path(sys.argv[1]).resolve()
PKG = OUT / "package"
typst = shutil.which("typst") or sys.exit("typst not found on PATH")
pdftotext = shutil.which("pdftotext") or r"C:\Program Files\Git\ucrt64\bin\pdftotext.exe"
problems = []


def run(cmd, what):
    r = subprocess.run(cmd, capture_output=True, text=True, encoding="utf-8", errors="replace")
    if r.returncode != 0:
        problems.append(f"{what}: {r.stderr.strip()[-300:]}")
        print("  !!  " + what)
        return False
    print("  ok  " + what)
    return True


def compile_typ(src, out):
    return run([typst, "compile", "--root", str(ROOT), str(src), str(out)], f"{src.relative_to(ROOT)} → {out.name}")


def pages(pdf):
    try:
        r = subprocess.run([pdftotext, str(pdf), "-"], capture_output=True, text=True, encoding="utf-8", errors="replace")
        if r.returncode == 0 and r.stdout:
            return r.stdout.count("\f")
    except FileNotFoundError:
        pass
    try:
        import pypdf
        return len(pypdf.PdfReader(str(pdf)).pages)
    except ImportError:
        return 0


for d in (PKG, PKG / "dxf", PKG / "3d"):
    d.mkdir(parents=True, exist_ok=True)

print("1. The drawings (compiled from the current sources)")
compile_typ(ROOT / "presentation.typ", PKG / "01_presentation.pdf")
compile_typ(ROOT / "design_gf.typ", PKG / "02_ground_floor_plan.pdf")
compile_typ(ROOT / "design_ff.typ", PKG / "03_first_floor_plan.pdf")
site = ROOT / "output" / "site_plan.pdf"
setout = ROOT / "output" / "setout.pdf"
compile_typ(ROOT / "studies" / "site_plan.typ", site)
compile_typ(ROOT / "studies" / "setout.typ", setout)
n1, n2 = pages(site), pages(setout)
if n1 and n2:
    merge = SRC / "site_and_setout.typ"
    body = ['// site_and_setout.typ · GENERATED by build_package.py: the site plan + the set-out sheet as one PDF (Typst 0.13+ embeds PDF pages as images)',
            '#set page(paper: "a4", flipped: true, margin: 0pt)']
    for n in range(1, n1 + 1):
        body.append(f'#image("../output/site_plan.pdf", page: {n}, width: 100%, height: 100%, fit: "contain")' + ('\n#pagebreak()' if n < n1 or n2 else ''))
    for n in range(1, n2 + 1):
        body.append(f'#image("../output/setout.pdf", page: {n}, width: 100%, height: 100%, fit: "contain")' + ('\n#pagebreak()' if n < n2 else ''))
    merge.write_text("\n".join(body) + "\n", encoding="utf-8")
    compile_typ(merge, PKG / "04_site_and_setout.pdf")
else:
    problems.append("site_and_setout: the page counts could not be read (pdftotext / pypdf missing)")

print("2. The DXFs (regenerated from the current data)")
for tool, name in (("make_dxf.py", "taif_ground_floor_V11.0.dxf"), ("make_dxf_ff.py", "taif_first_floor_V11.0.dxf"), ("make_dxf_roof.py", "taif_roof_V11.0.dxf")):
    ok = run([sys.executable, str(ROOT / "tools" / tool)], f"tools/{tool}")
    src = ROOT / "output" / name
    if src.exists():
        shutil.copy2(src, PKG / "dxf" / name)
        if not ok:
            problems.append(f"{name}: copied the latest file, NOT regenerated (mark it outdated in the README)")
    else:
        problems.append(f"{name}: missing")

print("3. The schedule, the decisions summary and the two briefs")
run([sys.executable, str(SRC / "make_schedule.py"), str(SRC / "room_schedule.csv")], "package_src/make_schedule.py")
shutil.copy2(SRC / "room_schedule.csv", PKG / "05_room_schedule.csv")
for src, out in (("room_schedule.typ", "05_room_schedule.pdf"), ("decisions_summary.typ", "06_decisions_summary.pdf"), ("structural_brief.typ", "07_structural_brief.pdf"), ("mep_brief.typ", "08_mep_brief.pdf")):
    compile_typ(SRC / src, PKG / out)
n = pages(PKG / "06_decisions_summary.pdf")
if n > 2:
    problems.append(f"06_decisions_summary.pdf has {n} pages (max 2)")

print("4. The 3D renders (3d/render_views.py; V11.0: rebuilt 17 Nov 2026)")
renders = sorted(p for p in (ROOT / "3d" / "output").glob("*.png") if p.name.startswith(("char_", "eye", "view_", "plan_")))
for p in renders:
    shutil.copy2(p, PKG / "3d" / p.name)
print(f"  ok  {len(renders)} renders copied")

print("5. README")
shutil.copy2(SRC / "README_package.md", OUT / "README.md")

print()
for p in sorted(PKG.rglob("*")):
    if p.is_file():
        print(f"  {p.relative_to(OUT)}  {p.stat().st_size / 1024:.0f} kB")
if problems:
    print("\nPROBLEMS:\n  " + "\n  ".join(problems))
    sys.exit(1)
print("\nPACKAGE BUILT")
